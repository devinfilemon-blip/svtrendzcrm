-- HRM module: employees, salary structures, payroll — run once if tables are missing

CREATE TABLE IF NOT EXISTS tblhr_employee (
  iEmployeeid INT AUTO_INCREMENT PRIMARY KEY,
  sFullName VARCHAR(150) NOT NULL,
  sEmployeeCode VARCHAR(50) NULL,
  sFatherName VARCHAR(150) NULL,
  dDob DATE NULL,
  iAge INT NULL,
  sBirthLocation VARCHAR(150) NULL,
  sGender VARCHAR(20) NULL,
  sBloodGroup VARCHAR(10) NULL,
  sMaritalStatus VARCHAR(20) NULL,
  sNomineeName VARCHAR(150) NULL,
  sNomineeRelation VARCHAR(100) NULL,
  sStatus VARCHAR(20) NOT NULL DEFAULT 'Active',
  iCreatedBy INT NULL,
  sCreatedTimeStamp DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sModifiedTimestamp DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_name (sFullName),
  INDEX idx_code (sEmployeeCode),
  INDEX idx_status (sStatus)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tblhr_salary_structure (
  iStructureid INT AUTO_INCREMENT PRIMARY KEY,
  iEmployeeid INT NOT NULL,
  dEffectiveFrom DATE NOT NULL,
  fBasicSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  fHRA DECIMAL(12,2) NOT NULL DEFAULT 0,
  fDA DECIMAL(12,2) NOT NULL DEFAULT 0,
  fTravelAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fMedicalAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fSpecialAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fOtherAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fPF DECIMAL(12,2) NOT NULL DEFAULT 0,
  fESI DECIMAL(12,2) NOT NULL DEFAULT 0,
  fProfessionalTax DECIMAL(12,2) NOT NULL DEFAULT 0,
  sTdsType VARCHAR(20) NOT NULL DEFAULT 'percent',
  fTdsValue DECIMAL(12,2) NOT NULL DEFAULT 0,
  fOtherDeduction DECIMAL(12,2) NOT NULL DEFAULT 0,
  fGrossSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  fTotalDeductions DECIMAL(12,2) NOT NULL DEFAULT 0,
  fNetSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  iCreatedBy INT NULL,
  sCreatedTimeStamp DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sModifiedTimestamp DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_emp (iEmployeeid),
  INDEX idx_effective (dEffectiveFrom)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tblhr_payroll (
  iPayrollid INT AUTO_INCREMENT PRIMARY KEY,
  iEmployeeid INT NOT NULL,
  iStructureid INT NULL,
  sPayMonth CHAR(7) NOT NULL,
  fBasicSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  fHRA DECIMAL(12,2) NOT NULL DEFAULT 0,
  fDA DECIMAL(12,2) NOT NULL DEFAULT 0,
  fTravelAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fMedicalAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fSpecialAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fOtherAllowance DECIMAL(12,2) NOT NULL DEFAULT 0,
  fPF DECIMAL(12,2) NOT NULL DEFAULT 0,
  fESI DECIMAL(12,2) NOT NULL DEFAULT 0,
  fProfessionalTax DECIMAL(12,2) NOT NULL DEFAULT 0,
  fTds DECIMAL(12,2) NOT NULL DEFAULT 0,
  fOtherDeduction DECIMAL(12,2) NOT NULL DEFAULT 0,
  fGrossSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  fTotalDeductions DECIMAL(12,2) NOT NULL DEFAULT 0,
  fNetSalary DECIMAL(12,2) NOT NULL DEFAULT 0,
  sStatus VARCHAR(20) NOT NULL DEFAULT 'Pending',
  dPaidDate DATE NULL,
  iCreatedBy INT NULL,
  sCreatedTimeStamp DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sModifiedTimestamp DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_emp_month (iEmployeeid, sPayMonth),
  INDEX idx_month (sPayMonth),
  INDEX idx_status (sStatus)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tblhr_advance (
  iAdvanceid INT AUTO_INCREMENT PRIMARY KEY,
  iEmployeeid INT NOT NULL,
  sType VARCHAR(50) NOT NULL DEFAULT 'Salary Advance',
  fAmount DECIMAL(12,2) NOT NULL DEFAULT 0,
  fMonthlyDeduction DECIMAL(12,2) NOT NULL DEFAULT 0,
  fRecovered DECIMAL(12,2) NOT NULL DEFAULT 0,
  dDate DATE NULL,
  sReason VARCHAR(255) NULL,
  sStatus VARCHAR(20) NOT NULL DEFAULT 'Active',
  iCreatedBy INT NULL,
  sCreatedTimeStamp DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sModifiedTimestamp DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_emp (iEmployeeid),
  INDEX idx_status (sStatus)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
